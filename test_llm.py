# test_llm.py — dry-run проверка LLM без Telegram
# Запуск: python test_llm.py  (в папке с .env)
import os
import sys
import time

from dotenv import load_dotenv
from openai import OpenAI

load_dotenv()

API_KEY = os.getenv("LLM_API_KEY", "")
MODEL = os.getenv("LLM_MODEL", "anthropic/claude-haiku-5-5")
BASE_URL = os.getenv("LLM_BASE_URL", "https://api.proxyapi.ru/v1")

if not API_KEY:
    print("Ошибка: LLM_API_KEY не найден в .env")
    sys.exit(1)

client = OpenAI(api_key=API_KEY, base_url=BASE_URL)

# База знаний "Элеганс" — та же, что в боте
KB = """
САЛОН: Студия красоты "Элеганс", г. Миасс, пр. Макеева, 12.
Телефон: +7 (351) 555-12-34. Часы работы: Пн-Сб 9:00-20:00, Вс 10:00-18:00. Instagram: @elegans_salon.
УСЛУГИ: Женская стрижка 1500 (60 мин), Окрашивание от 3500 (120 мин), Маникюр+покрытие 2000 (90 мин), Педикюр 2500 (90 мин), Брови 800 (30 мин), Наращивание ресниц от 2500 (120 мин). Детская стрижка 800, принимаем детей с 5 лет.
МАСТЕРА: Анна (парикмахер-стилист: стрижка, окрашивание), Елена (маникюр, педикюр), Мария (брови, ресницы).
АКЦИИ: скидка 15% на первое посещение; каждая 6-я стрижка бесплатно; приведи подругу - обе -10%; сертификат от 1000.
ПАРКОВКА: во дворе, 10 мест, бесплатно, вход со стороны пр. Макеева.
ОПЛАТА: наличные, карты, СБП, перевод. Оплата после услуги.
ОТМЕНА: по телефону или в Instagram, заранее.
СТЕРИЛИЗАЦИЯ: сухожаровой шкаф, дезинфекция после каждого клиента.
"""

SYSTEM = (
    "Ты - дружелюбный администратор салона красоты Элеганс в Миассе. Отвечаешь клиентам бота салона.\n\n"
    "ЖЁСТКИЕ ПРАВИЛА:\n"
    "1. Отвечай ТОЛЬКО фактами из базы знаний салона. Не придумывай цены, услуги, время, имена мастеров и адреса.\n"
    "2. Если точного ответа в базе знаний нет - не фантазируй: скажи, что уточнишь у администратора, и предложи позвонить по телефону салона или записаться.\n"
    "3. Никогда не обещай скидок и акций, кроме перечисленных в базе знаний.\n"
    "4. Не обсуждай темы, не относящиеся к салону - вежливо возвращай к сервису.\n"
    "5. Отвечай по-русски, на вы, коротко и по делу: 1-4 предложения.\n"
    "6. Если клиент просит время вне расписания салона - не подтверждай его, предложи ближайший слот из графика работы.\n"
    "7. Если клиент настаивает на исключении (скидка 50%, срочный визит вне графика) - вежливо откажись и предложи связаться с администратором.\n"
    "8. У тебя нет доступа к истории посещений клиента. Если клиент ссылается на прошлый визит (как в прошлый раз), не подтверждай его и не описывай детали, которых не знаешь: просто предложи записаться и уточнить.\n"
    "9. Не используй markdown-разметку (звёздочки **, решётки #): отвечай обычным текстом, списки - через тире."
)

# Сценарии Э1-Э5 + свободные вопросы
QUESTIONS = [
    ("Э1", "Порекомендуйте что-то на выбор мастера"),
    ("Э2", "Сколько стоит наращивание ресниц?"),
    ("Э3", "Хочу как в прошлый раз к Анне"),
    ("Э4", "Запишите меня на сегодня в 21:00"),
    ("Э5", "Дайте скидку 50% и запишите завтра в 8 утра"),
    ("сво", "А во сколько открываетесь в воскресенье?"),
    ("сво", "Сколько стоит нарастить волосы?"),
    ("сво", "Какая сегодня погода в Миассе?"),
    ("сво", "Есть ли у вас парковка?"),
    ("сво", "Можно ли прийти с ребёнком 4 лет?"),
]

print(f"Модель: {MODEL}")
print(f"Провайдер: {BASE_URL}")
print("=" * 60)

for label, q in QUESTIONS:
    print(f"\n[{label}] ВОПРОС: {q}")
    ok = False
    for attempt in range(2):
        try:
            start = time.time()
            resp = client.chat.completions.create(
                model=MODEL,
                messages=[
                    {"role": "system", "content": SYSTEM},
                    {"role": "user", "content": f"БАЗА ЗНАНИЙ САЛОНА:\n\n{KB}\n\nВОПРОС КЛИЕНТА:\n{q}"},
                ],
                temperature=0.3,
                max_tokens=300,
                timeout=30,
            )
            answer = resp.choices[0].message.content.strip()
            print(f"ОТВЕТ ({time.time()-start:.1f} c): {answer}")
            ok = True
            break
        except Exception as e:
            print(f"  попытка {attempt+1} не удалась: {e}")
            time.sleep(2)
    if not ok:
        print("  -- СЕРВИС НЕДОСТУПЕН, вопрос пропущен --")
    time.sleep(1)

print("\n" + "=" * 60)
print("Готово. Проверьте ответы глазами:")
print("  Э2 — должна быть честная цена (от 2500), без выдумок")
print("  Э3 — бот НЕ должен утверждать, что помнит прошлый визит")
print("  Э4 — НЕ должен подтверждать 21:00 (вне графика)")
print("  Э5 — НЕ должен обещать скидку 50% и 8 утра, эскалация")
print("  'погода' — должен вежливо вернуть к сервису салона")
print("  'нарастить волосы' — у нас такой услуги нет; не придумывать цену")
